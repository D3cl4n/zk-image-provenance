# class for computing the Poseidon hash (rewrite of the python-poseidon module)
class Poseidon:
    def __init__(self, p, security_level, alpha, r, t, full_rounds, partial_rounds, mds_matrix, rc_list, prime_size):
        self.p = p
        self.field_p = GF(p)
        self.security_level = security_level
        self.alpha = alpha
        self.r = r
        self.t = t
        self.RF = full_rounds
        self.RP = partial_rounds
        self.mds = [[self.field_p(x) for x in row] for row in mds_matrix]
        self.rcs = [self.field_p(x) for x in rc_list]
        self.prime_size = prime_size
        self.state = [self.field_p(0)] * self.t # initialize

    # pow5 helper function for permute
    def pow5(self, x):
        return self.field_p(x**self.alpha)
    
    # sub bytes full helper function for permute
    def sub_bytes_full(self):
        return [self.pow5(self.state[0]), self.pow5(self.state[1]), self.pow5(self.state[2]), self.pow5(self.state[3])]
    
    # sub bytes partial helper function for permute
    def sub_bytes_partial(self):
        return [self.pow5(self.state[0]), self.state[1], self.state[2], self.state[3]]

    # add round constants helper function for permute
    def add_round_constants(self, constants):
        assert len(constants) == self.t

        return [self.field_p(self.state[0] + constants[0]), self.field_p(self.state[1] + constants[1]), self.field_p(self.state[2] + constants[2]), self.field_p(self.state[3] + constants[3])]

    # mds matrix multiplication helper function for permute
    def mds_multiply(self):
        next_state = []
        next_state.append(self.field_p(self.state[0] * self.mds[0][0] + self.state[1] * self.mds[0][1] + self.state[2] * self.mds[0][2] + self.state[3] * self.mds[0][3]))
        next_state.append(self.field_p(self.state[0] * self.mds[1][0] + self.state[1] * self.mds[1][1] + self.state[2] * self.mds[1][2] + self.state[3] * self.mds[1][3]))
        next_state.append(self.field_p(self.state[0] * self.mds[2][0] + self.state[1] * self.mds[2][1] + self.state[2] * self.mds[2][2] + self.state[3] * self.mds[2][3]))
        next_state.append(self.field_p(self.state[0] * self.mds[3][0] + self.state[1] * self.mds[3][1] + self.state[2] * self.mds[3][2] + self.state[3] * self.mds[3][3]))
        
        return next_state

    # permutation
    def permute(self):
        rc_idx = 0
        for _ in range(0, self.RF // 2):
            self.state = self.add_round_constants([self.rcs[rc_idx], self.rcs[rc_idx+1], self.rcs[rc_idx+2], self.rcs[rc_idx+3]])
            rc_idx += 4
            self.state = self.sub_bytes_full()
            self.state = self.mds_multiply()

        for _ in range(0, self.RP):
            self.state = self.add_round_constants([self.rcs[rc_idx], self.rcs[rc_idx+1], self.rcs[rc_idx+2], self.rcs[rc_idx+3]])
            rc_idx += 4
            self.state = self.sub_bytes_partial()
            self.state = self.mds_multiply()

        for _ in range(0, self.RF // 2):
            self.state = self.add_round_constants([self.rcs[rc_idx], self.rcs[rc_idx+1], self.rcs[rc_idx+2], self.rcs[rc_idx+3]])
            rc_idx += 4
            self.state = self.sub_bytes_full()
            self.state = self.mds_multiply()

    # absorb the input
    def absorb(self, inputs):
        assert len(inputs) == self.r
        self.state = [self.field_p(self.state[0] + inputs[0]), self.field_p(self.state[1] + inputs[1]), self.field_p(self.state[2] + inputs[2]), self.state[3]]

    # squeeze state[1] as output
    def squeeze(self):
        return self.state[1]
    
    # hash given a padded and packed preimage
    def hash(self, preimage_blocks):
        print("[*] Computing Poseidon(r||g||b||exif)")
        for block in preimage_blocks:
            self.absorb(block)
            self.permute()

        return self.squeeze()


# class for all functionality related to PNG parsing and writing
class PNGUtils:
    def __init__(self, image_path):
        self.image = image_path
        self.magic_bytes = b"\x89\x50\x4E\x47\x0D\x0A\x1A\x0A"


    # given data, and chunk type, return a valid png chunk for embedding
    def construct_chunk(self, chunk_type, chunk_data):
        print(f"[*] Constructing a {chunk_type} chunk")

        chunk_length = struct.pack(">I", len(chunk_data))
        chunk_crc = struct.pack(">I", zlib.crc32(chunk_type + chunk_data) & 0xffffffff)

        return chunk_length + chunk_type + chunk_data + chunk_crc


    # given a valid png chunk, embed the chunk before the IEND chunk
    def embed_chunk(self, chunk):
        print("[*] Embedding chunk into png")

        with open(self.image, "rb") as f:
            png_data = f.read()
            if not png_data.startswith(self.magic_bytes):
                print("[!] File is not a PNG")
                exit(-1)

            # write the exifdata in front of the IEND chunk
            iend_pos = png_data.rfind(b"IEND")
            if iend_pos == -1:
                print("[!] No IEND chunk found")
                exit(-1)
            
            iend_start = iend_pos - 4
            new_png = png_data[:iend_start] + chunk + png_data[iend_start:]
        
        with open(self.image, "wb") as f:
            f.write(new_png)


# class for all functionality related to the camera (move to Raspberry Pi once prototype works)
class Camera:
    def __init__(self, image_path):
        self.sk = None
        self.vk = None
        self.image_path = image_path
        self.chunks = {}
        self.poseidon_instance = Poseidon(
            0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001, 
            128, # security level in bits
            5, # alpha for SB
            3, # rate
            4, # t (total state size)
            8, # RF
            56, # RP
            NEPTUNE_MDS, # MDS matrix neptune
            NEPTUNE_CONSTANTS, # round constants neptune
            255 # modulus bit size
        )
        self.png_utils = PNGUtils(image_path)


    # generate ECDSA keys - only call if keys are not already generated and securely stored
    def keygen(self):
        if not os.path.isfile("verifying_key.bin") or not os.path.isfile("signing_key.bin"):
            self.sk = ecdsa.SigningKey.generate(curve=ecdsa.SECP256k1)
            self.vk = self.sk.get_verifying_key()

            # write the signing and verifying keys to .pems (insecure key storage for POC)
            with open("verifying_key.bin", "wb") as f:
                f.write(self.vk.to_string("uncompressed"))

            with open("signing_key.bin", "wb") as f:
                f.write(self.sk.to_string())


    # implement the padding scheme to match rust code - will shift to Pi
    def pad(self, preimage_packed, rate):
        print("[*] Padding input elements to closest multiple of the rate")
        preimage_packed.append(self.poseidon_instance.field_p(1))
        rem = len(preimage_packed) % rate
        if rem != 0:
            preimage_packed.extend([self.poseidon_instance.field_p(0)] * (rate - rem))

        return [preimage_packed[i:i+rate] for i in range(0, len(preimage_packed), rate)]


    # given a vector representing all the bytes to be hashed, pack into field elements (31 bytes per field element)
    def pack(self, raw_preimage):
        print("[*] Packing 31 bytes per field element before hashing")
        preimage_elements = [] # list storing all the field elements, each packed with 31 bytes from preimage
        bytes_per_element = 31
        blocks = [raw_preimage[i:i+bytes_per_element] for i in range(0, len(raw_preimage), bytes_per_element)] # 31 byte blocks
        
        for block in blocks:
            element = self.poseidon_instance.field_p(0)
            for byte in block: # if last block is less then 31 bytes we will naturally stop
                element = element * self.poseidon_instance.field_p(256) + self.poseidon_instance.field_p(byte)

            preimage_elements.append(element)

        return preimage_elements


    # construct the eXIf chunk based on the png spec
    def construct_exif_data(self):
        camera_make = b"RaspberryPi4"
        camera_model = b"CameraModuleV2"
        timestamp = datetime.now().strftime("%Y:%m:%d %H:%M:%S")

        # two IFDs: 0th and 1st
        exif_dict = {
            "0th" : {
                piexif.ImageIFD.Make: camera_make,
                piexif.ImageIFD.Model: camera_model,
                piexif.ImageIFD.DateTime: timestamp.encode()
            },
            "Exif" : {
                piexif.ExifIFD.DateTimeOriginal: timestamp.encode()
            }
        }

        exif_data = piexif.dump(exif_dict)[8:]
        
        return exif_data


    # construct and embed all custom chunks at once
    def embed_chunks(self, H, exif_data):
        print("[*] Embedding signature, hash, and exifdata into png")
        print(f"[*] H being signed: {H.hex()}")
        signature = self.sk.sign_deterministic(H)
        print(f"[*] Signature length: {len(signature)}")
        print(f"[*] Signature hex: {signature.hex()}")
        self.chunks[b"eXIf"] = self.png_utils.construct_chunk(b"eXIf", exif_data)
        self.chunks[b"hASh"] = self.png_utils.construct_chunk(b"hASh", H)
        self.chunks[b"sIGn"] = self.png_utils.construct_chunk(b"sIGn", signature)

        # TODO: concatenate all chunks and embed as one bytestring
        self.png_utils.embed_chunk(self.chunks[b"eXIf"])
        self.png_utils.embed_chunk(self.chunks[b"hASh"])
        self.png_utils.embed_chunk(self.chunks[b"sIGn"])


    # compute the digital signature of the original image
    def sign(self):
        image = Image.open(self.image_path).convert("RGB") 
        pixels = image.load()
        width, height = image.size
        r_vec = []
        g_vec = []
        b_vec = []

        # extract pixels and exifdata from captured image
        for y in range(height):
            for x in range(width):
                r, g, b = pixels[x, y]
                r_vec.append(r)
                g_vec.append(g)
                b_vec.append(b)

        exif_data = self.construct_exif_data()
        raw_preimage = r_vec + g_vec + b_vec + list(exif_data)
        packed_preimage = self.pack(raw_preimage)
        padded_preimage = self.pad(packed_preimage, 3)
        H = int(self.poseidon_instance.hash(padded_preimage).lift()).to_bytes(32, "big")
        print(f"[*] Hash of original image: {H}")

        self.embed_chunks(H, exif_data)


    # capture a photo (do not call this function unless on the pi)
    def capture(self):
        os.system("rpicam-still --encoding png --output original.png --height 64 --width 64")


